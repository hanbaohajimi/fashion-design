import { openCanvasFunction } from "./canvas-function-navigation";
import { mkdir, readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import { canvasMediaFixture, mediaCard, mediaPanel, openMediaFiles } from "./canvas-media-fixture";
import { loadZhiya } from "./zhiya-fixture";
test.skip(process.env.CANVAS_MEDIA_DEMO !== "1", "独立画面与短录屏展示");
test.setTimeout(60_000);
test.use({ video: { mode: "on", size: { width: 1440, height: 900 } }, trace: "off" });
for (const width of [1440, 320]) test(`${width}px媒体卡片的放置、播放、详情与回到创作`, async ({ page }) => {
  await mkdir("output/playwright/canvas-media", { recursive: true });
  const demoVideo = await readFile("output/playwright/canvas-media/garment-demo.mp4");
  const state = await canvasMediaFixture(page, { width, canvasCount: 6, demoVideo });
  await loadZhiya(page); await openMediaFiles(page);
  const row = mediaPanel(page).locator('[data-generated-file-id="runway:result-3"]');
  await row.getByRole("button", { name: "放入画布", exact: true }).click();
  await row.getByRole("button", { name: "查看已放入的媒体", exact: true }).click();
  await expect(mediaPanel(page)).toHaveCount(0);
  const card = mediaCard(page);
  await card.locator("video").evaluate((element: HTMLVideoElement) => { element.loop = true; });
  await card.getByRole("button", { name: "播放 秋冬服装秀成片", exact: true }).click();
  await expect.poll(() => card.locator("video").evaluate((element: HTMLVideoElement) => !element.paused && element.currentTime > 0)).toBe(true);
  await page.waitForTimeout(2200);
  await page.screenshot({ path: `output/playwright/canvas-media/garment-${width}.png` });
  await openCanvasFunction(page, "画布对象");
  const objects = page.getByRole("region", { name: "画布对象", exact: true });
  await objects.getByRole("searchbox", { name: "查找画布对象" }).fill("秋冬服装秀成片");
  await objects.getByRole("button", { name: "选择 秋冬服装秀成片", exact: true }).click();
  await objects.getByRole("button", { name: "置于顶层", exact: true }).click();
  await objects.getByRole("button", { name: "关闭画布对象", exact: true }).click();
  await page.getByRole("button", { name: "查看详情", exact: true }).click();
  await expect(page.getByRole("region", { name: "媒体来源", exact: true })).toContainText("不会自动分析");
  await page.waitForTimeout(1000);
  expect(state.placements).toHaveLength(1); expect(state.errors).toEqual([]);
  const recording = page.video(); await page.close(); await recording?.saveAs(`output/playwright/canvas-media/tour-${width}.webm`);
});
